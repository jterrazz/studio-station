package catalog

type Level string

const (
	LevelCache  Level = "cache"
	LevelData   Level = "data"
	LevelConfig Level = "config"
	LevelKept   Level = "kept"
)

var Levels = []Level{LevelCache, LevelData, LevelConfig, LevelKept}

type Stored struct {
	Path  string
	Level Level
	On    []MachineKind
	Note  string
	Memos []string
}

type Action struct {
	Run    []string
	Env    []string
	Delete []string
	Prune  []string
	Needs  string
	Exists string
	On     []MachineKind
}

type ToolFile string

const (
	FileGoEnv  ToolFile = "go-env"
	FileNpmrc  ToolFile = "npmrc"
	FileBunfig ToolFile = "bunfig"
	FileMise   ToolFile = "mise config"
)

type Relocation struct {
	File    ToolFile
	Key     string
	Value   string
	Pending string
}

type Move struct{ From, To string }

type Stray struct {
	Path  string
	Busy  string
	Move  []Move
	Prune []string
	Then  []string
	Clean []Action
}

type SizeProbe string

const (
	SizeDirs     SizeProbe = ""
	SizeDockerDF SizeProbe = "docker-system-df"
)

type Storage struct {
	Paths     []Stored
	Installed []string
	Removal   map[string]string
	Size      SizeProbe
	Clean     []Action
	Reset     []Action
	NoReset   string
	Quit      string
	Relocate  []Relocation
	Strays    []Stray
}

func (s Storage) Declared() bool {
	return len(s.Paths) > 0 || len(s.Installed) > 0 || len(s.Clean) > 0 || len(s.Strays) > 0 || s.Size != SizeDirs
}

type Exception struct{ Path, Reason string }

func (s Stored) PlacedOn(k MachineKind) bool { return placedOn(s.On, k) }

func (a Action) PlacedOn(k MachineKind) bool { return placedOn(a.On, k) }

func placedOn(on []MachineKind, k MachineKind) bool {
	if len(on) == 0 {
		return true
	}
	for _, kind := range on {
		if kind == k {
			return true
		}
	}
	return false
}

func cache(path string, on ...MachineKind) Stored {
	return Stored{Path: path, Level: LevelCache, On: on}
}
func data(path string, on ...MachineKind) Stored { return Stored{Path: path, Level: LevelData, On: on} }
func conf(path string, on ...MachineKind) Stored {
	return Stored{Path: path, Level: LevelConfig, On: on}
}
func kept(path string, on ...MachineKind) Stored { return Stored{Path: path, Level: LevelKept, On: on} }

func noted(s Stored, note string) Stored { s.Note = note; return s }

func memos(s Stored, patterns ...string) Stored { s.Memos = patterns; return s }

func runIf(needs string, argv ...string) Action { return Action{Run: argv, Needs: needs} }

func ifExists(a Action, path string) Action { a.Exists = path; return a }

func remove(patterns ...string) Action { return Action{Delete: patterns} }

func onMac(a Action) Action { a.On = macKinds; return a }

func onLinux(a Action) Action { a.On = []MachineKind{Linux}; return a }

