package main

import (
	"encoding/json"
	"fmt"
	"maps"
	"reflect"
	"slices"
	"strings"
	"unicode"
)

const typesHeader = "// Generated by `make generate` (apps/engine/cmd/generate) from the JSON Schemas of packages/api/schemas: do not edit.\n"

// value: a schema's name in TypeScript: each part of its key capitalised,
// `core.machine.Kind` is CoreMachineKind.
func tsName(key string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(key, func(r rune) bool { return r == '.' || r == '-' || r == '_' }) {
		r := []rune(part)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

// invariant: the TypeScript is the schemas', and only theirs: every $defs of
// every file once (a key two files share must say the same thing), then each
// call's in and out by its name, then the map a client's call is typed by.
func typescript(calls []wireCall, docs map[string]map[string]any, more ...map[string]any) []byte {
	defs := map[string]any{}
	gather := func(doc map[string]any) {
		d, _ := doc["$defs"].(map[string]any)
		for k, v := range d {
			if prior, seen := defs[k]; seen && !reflect.DeepEqual(canonical(prior), canonical(v)) {
				panic("two schemas define " + k + " differently")
			}
			defs[k] = v
		}
	}
	for _, c := range calls {
		gather(docs[c.meta.Name])
	}
	for _, doc := range more {
		gather(doc)
	}
	named := map[string]string{}
	taken := map[string]string{}
	claim := func(name, by string) {
		if prior, ok := taken[name]; ok {
			panic("the TypeScript name " + name + " is both " + prior + " and " + by)
		}
		taken[name] = by
	}
	for k := range defs {
		named[k] = tsName(k)
		claim(named[k], k)
	}
	var b strings.Builder
	b.WriteString(typesHeader)
	keys := slices.SortedFunc(maps.Keys(defs), func(a, b string) int { return strings.Compare(named[a], named[b]) })
	for _, k := range keys {
		b.WriteString("\nexport type " + named[k] + " = " + tsOf(object(defs[k]), named, 0) + ";\n")
	}
	b.WriteString("\n")
	entries := make([]string, 0, len(calls))
	for _, c := range calls {
		props := object(docs[c.meta.Name]["properties"])
		base := tsName(c.meta.Name)
		for _, side := range [][2]string{{"in", "Input"}, {"out", "Output"}} {
			name := base + side[1]
			schema := object(props[side[0]])
			if ref, ok := schema["$ref"].(string); ok && named[strings.TrimPrefix(ref, "#/$defs/")] == name {
				continue
			}
			claim(name, c.meta.Name+" "+side[0])
			b.WriteString("export type " + name + " = " + tsOf(schema, named, 0) + ";\n")
		}
		entry := "    '" + c.meta.Name + "': { in: " + base + "Input; out: " + base + "Output; watch: " + boolean(c.meta.Watch)
		if c.meta.Confirm != "" {
			entry += "; confirm: '" + string(c.meta.Confirm) + "'"
		}
		if c.own {
			entry += "; own: true"
		}
		entries = append(entries, entry+" };\n")
	}
	b.WriteString("\nexport interface Calls {\n" + strings.Join(entries, "") + "}\n")
	b.WriteString("\nexport type CallName = keyof Calls;\n")
	return []byte(b.String())
}

// value: a schema node the generator itself wrote, which is always an object.
func object(v any) map[string]any {
	m, ok := v.(map[string]any)
	if !ok {
		panic(fmt.Sprintf("a schema node is %T, not an object", v))
	}
	return m
}

func list(v any) []any {
	l, ok := v.([]any)
	if !ok {
		panic(fmt.Sprintf("a schema list is %T, not an array", v))
	}
	return l
}

func boolean(v bool) string {
	if v {
		return "true"
	}
	return "false"
}

func canonical(v any) any {
	data, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	var out any
	if err := json.Unmarshal(data, &out); err != nil {
		panic(err)
	}
	return out
}

func literal(v any) string {
	if s, ok := v.(string); ok {
		return "'" + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), "'", `\'`) + "'"
	}
	data, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	return string(data)
}

func union(parts []string) string {
	return strings.Join(slices.Compact(parts), " | ")
}

func tsOf(s map[string]any, named map[string]string, depth int) string {
	if ref, ok := s["$ref"].(string); ok {
		return named[strings.TrimPrefix(ref, "#/$defs/")]
	}
	if v, ok := s["const"]; ok {
		return literal(v)
	}
	if enum, ok := s["enum"]; ok {
		var parts []string
		for _, v := range list(canonical(enum)) {
			parts = append(parts, literal(v))
		}
		return union(parts)
	}
	if alts, ok := s["anyOf"].([]any); ok {
		var parts []string
		for _, a := range alts {
			parts = append(parts, tsOf(object(a), named, depth))
		}
		return union(parts)
	}
	switch t := s["type"].(type) {
	case []any:
		var parts []string
		for _, one := range t {
			alone := maps.Clone(s)
			alone["type"] = one
			parts = append(parts, tsOf(alone, named, depth))
		}
		return union(parts)
	case string:
		switch t {
		case "string":
			return "string"
		case "integer", "number":
			return "number"
		case "boolean":
			return "boolean"
		case "null":
			return "null"
		case "array":
			item := tsOf(object(s["items"]), named, depth)
			if strings.Contains(item, " | ") || strings.Contains(item, "\n") && !strings.HasPrefix(item, "{") {
				item = "(" + item + ")"
			}
			return item + "[]"
		case "object":
			return tsObject(s, named, depth)
		}
	}
	if len(s) == 0 {
		return "unknown"
	}
	panic("no TypeScript for the schema " + string(indented(s)))
}

func tsObject(s map[string]any, named map[string]string, depth int) string {
	props, _ := s["properties"].(map[string]any)
	if extra, ok := s["additionalProperties"].(map[string]any); ok && len(props) == 0 {
		return "Record<string, " + tsOf(extra, named, depth) + ">"
	}
	if len(props) == 0 {
		return "Record<string, never>"
	}
	required := map[string]bool{}
	switch r := s["required"].(type) {
	case []string:
		for _, k := range r {
			required[k] = true
		}
	case []any:
		for _, k := range r {
			if name, ok := k.(string); ok {
				required[name] = true
			}
		}
	}
	indent := strings.Repeat("    ", depth+1)
	var b strings.Builder
	b.WriteString("{\n")
	for _, k := range slices.Sorted(maps.Keys(props)) {
		key := k
		if !identifier(k) {
			key = literal(k)
		}
		if !required[k] {
			key += "?"
		}
		b.WriteString(indent + key + ": " + tsOf(object(props[k]), named, depth+1) + ";\n")
	}
	b.WriteString(strings.Repeat("    ", depth) + "}")
	return b.String()
}

func identifier(k string) bool {
	for i, r := range k {
		if r != '_' && r != '$' && !unicode.IsLetter(r) && (i == 0 || !unicode.IsDigit(r)) {
			return false
		}
	}
	return k != ""
}
