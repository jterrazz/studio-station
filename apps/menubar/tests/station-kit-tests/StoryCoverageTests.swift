import Foundation
import StationKit
import XCTest

struct Catalogue {
    struct Entry: Equatable {
        let id: String
        let section: String
    }

    let entries: [Entry]

    var ids: [String] { entries.map(\.id) }

    static func parse(_ markdown: String) -> Catalogue {
        var section = ""
        var entries: [Entry] = []
        for line in markdown.split(separator: "\n", omittingEmptySubsequences: false) {
            if line.hasPrefix("## ") { section = String(line.dropFirst(3)) }
            if line.hasPrefix("### `"), let end = line.dropFirst(5).firstIndex(of: "`") {
                entries.append(Entry(id: String(line.dropFirst(5)[..<end]), section: section))
            }
        }
        return Catalogue(entries: entries)
    }
}

struct Coverage {
    struct Tally: Equatable {
        var green = 0
        var pending = 0
        var orphans = 0
    }

    // value: SPEC C6's gap ids: IA states the prototype does not draw yet,
    // pending in the output until each is designed into STORIES.md.
    static let gaps = [
        "mac.unreachable", "mac.disk-locked", "engine.stopped", "server.loop",
        "section.apps", "section.settings", "section.disk", "section.background",
        "sheet.move-folder", "mac.disk-low", "mac.ready.failing", "server.activity.silent",
        "mac.many-workspaces", "home.many-macs", "mac.mini.stale", "workspace.hook-missing",
    ]

    let ids: [String]
    let excluded: [String]
    let pending: [String]
    let files: [String: Bool]
    let goldens: [String]

    static func goldenID(_ name: String) -> String? {
        guard name.hasSuffix(".png") else { return nil }
        var parts = name.dropLast(4).split(separator: ".", omittingEmptySubsequences: false).map(String.init)
        if parts.last == "actual" { parts.removeLast() }
        guard let scheme = parts.last, scheme == "dark" || scheme == "light" else { return nil }
        parts.removeLast()
        if let knob = parts.last, knob == "ic" || knob == "rt" { parts.removeLast() }
        return parts.isEmpty ? nil : parts.joined(separator: ".")
    }

    func green(_ id: String) -> Bool {
        guard files[id] == false else { return false }
        return goldens.contains("\(id).dark.png") && goldens.contains("\(id).light.png")
    }

    func status(_ id: String) -> String {
        if excluded.contains(id) { return "excluded" }
        if green(id) { return "green" }
        return files[id] == true ? "today" : "pending"
    }

    // invariant: PLAN §0's ratchet: every id of STORIES.md is green or
    // pending, a green id has left PENDING, and nothing names an id
    // STORIES.md does not hold.
    func audit() -> (findings: [String], tally: Tally) {
        var findings: [String] = []
        var tally = Tally()
        let held = Set(ids).subtracting(excluded)
        var seen = Set<String>()
        for id in pending where !seen.insert(id).inserted { findings.append("\(id): listed twice in PENDING") }
        for id in ids where held.contains(id) {
            if green(id) {
                tally.green += 1
                if pending.contains(id) { findings.append("\(id): green, so its line leaves PENDING") }
            } else {
                tally.pending += 1
                if !pending.contains(id) { findings.append("\(id): neither green nor in PENDING") }
            }
        }
        for id in excluded where !ids.contains(id) { findings.append("\(id): excluded, but STORIES.md does not hold it") }
        var orphans: [String] = []
        for id in pending where !held.contains(id) { orphans.append("\(id): in PENDING, but STORIES.md does not hold it") }
        for id in files.keys.sorted() where !held.contains(id) { orphans.append("\(id): a story file STORIES.md does not hold") }
        for name in goldens.sorted() {
            guard let id = Self.goldenID(name) else {
                orphans.append("\(name): not a golden of a story")
                continue
            }
            if !held.contains(id) { orphans.append("\(name): a golden STORIES.md does not hold") }
        }
        tally.orphans = orphans.count
        return (findings + orphans, tally)
    }

    func index(_ catalogue: Catalogue, stories: [String: StoryFile]) throws -> String {
        var out = """
        # The stories, mapped to their pages and UI state

        Generated by `StoryCoverageTests` from `STORIES.md`, `PENDING`, `EXCLUDED` and the story files; \
        do not edit. `make generate` rewrites it.

        """
        var section: String?
        for entry in catalogue.entries {
            if entry.section != section {
                section = entry.section
                out += "\n## \(entry.section)\n\n| Story | Status | Pages | UI |\n| --- | --- | --- | --- |\n"
            }
            let story = stories[entry.id]
            let pages = story?.pages.map { "`\($0)`" }.joined(separator: ", ") ?? ""
            var ui = ""
            if let state = story?.ui {
                let encoder = JSONEncoder()
                encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
                ui = "`" + String(decoding: try encoder.encode(state), as: UTF8.self) + "`"
            }
            out += "| `\(entry.id)` | \(status(entry.id)) | \(pages) | \(ui) |\n"
        }
        let gaps = Self.gaps.filter { !ids.contains($0) }
        out += "\n## Gaps, pending until designed\n\n" + gaps.map { "- `\($0)`\n" }.joined()
        return out
    }
}

final class StoryCoverageTests: XCTestCase {
    static let update = ProcessInfo.processInfo.environment["STATION_UPDATE_INDEX"] == "1"

    func lines(_ name: String) throws -> [String] {
        try String(contentsOf: Tree.stories.appendingPathComponent(name), encoding: .utf8)
            .split(separator: "\n").map { $0.trimmingCharacters(in: .whitespaces) }.filter { !$0.isEmpty }
    }

    func catalogue() throws -> Catalogue {
        Catalogue.parse(try String(contentsOf: Tree.stories.appendingPathComponent("STORIES.md"), encoding: .utf8))
    }

    func excluded() throws -> [String] {
        try lines("EXCLUDED").map { String($0.prefix { $0 != ":" }) }
    }

    func stories() throws -> [String: StoryFile] {
        var out: [String: StoryFile] = [:]
        for file in try Stories.files(root: Tree.stories) { out[Stories.id(of: file)] = try Stories.read(file) }
        return out
    }

    func coverage() throws -> Coverage {
        let goldens = (try? FileManager.default.contentsOfDirectory(atPath: Tree.storyGoldens.path)) ?? []
        return Coverage(ids: try catalogue().ids, excluded: try excluded(), pending: try lines("PENDING"),
                        files: try stories().mapValues(\.today), goldens: goldens.filter { $0.hasSuffix(".png") })
    }

    func testEveryStoryIsGreenOrPending() throws {
        let coverage = try coverage()
        XCTAssertEqual(coverage.ids.count, 178, "STORIES.md holds the 178 stories of v4, A2 the 19 it added and the 9 it retired")
        let (findings, tally) = coverage.audit()
        let gaps = Coverage.gaps.filter { !coverage.ids.contains($0) }
        print("stories: \(tally.pending) pending, \(tally.green) green, \(tally.orphans) orphans; \(gaps.count) gap ids pending: \(gaps.joined(separator: ", "))")
        XCTAssertEqual(findings, [])
    }

    func testOnlyThePrototypesOwnPageIsExcluded() throws {
        XCTAssertEqual(try excluded(), ["phone.explainer"])
        for line in try lines("EXCLUDED") {
            XCTAssertTrue(line.contains(": ") && line.split(separator: ":", maxSplits: 1)[1].count > 3, "\(line): an exclusion names its reason")
        }
    }

    func testEveryStoryFileLoadsWithItsPages() throws {
        let files = try Stories.files(root: Tree.stories)
        let loaded = try Stories.load(root: Tree.stories)
        XCTAssertEqual(loaded.map(\.id), files.map(Stories.id(of:)))
        for story in loaded { XCTAssertEqual(story.pages.count, story.file.pages.count, story.id) }
    }

    func testTheIndexIsTheCatalogueAsItStands() throws {
        let want = try coverage().index(try catalogue(), stories: try stories())
        let file = Tree.stories.appendingPathComponent("INDEX.md")
        if Self.update { try want.write(to: file, atomically: true, encoding: .utf8) }
        let have = (try? String(contentsOf: file, encoding: .utf8)) ?? ""
        XCTAssertTrue(have == want, "INDEX.md drifted from the stories: make generate rewrites it")
    }

    static func previews(_ ids: [String]) -> String {
        """
        // Generated by StoryCoverageTests from the story files; do not edit. `make generate` rewrites it.
        #if DEBUG
        import SwiftUI

        """ + ids.map { "\n#Preview(\"\($0)\") { StoryStage(Stories[\"\($0)\"]) }\n" }.joined() + "\n#endif\n"
    }

    func testEveryStoryFileHasItsXcodePreview() throws {
        let want = Self.previews(try Stories.files(root: Tree.stories).map(Stories.id(of:)))
        let file = Tree.sources.appendingPathComponent("catalog/Previews.generated.swift")
        if Self.update { try want.write(to: file, atomically: true, encoding: .utf8) }
        let have = (try? String(contentsOf: file, encoding: .utf8)) ?? ""
        XCTAssertTrue(have == want, "Previews.generated.swift drifted from the story files: make generate rewrites it")
    }

    func testTheRatchetCatchesWhatItForbids() {
        let coverage = Coverage(
            ids: ["home.a", "home.b", "home.c", "home.d", "phone.explainer"],
            excluded: ["phone.explainer"],
            pending: ["home.b", "home.c", "home.c", "home.gone"],
            files: ["home.b": false, "home.c": true, "home.d": false, "home.stray": false],
            goldens: ["home.b.dark.png", "home.b.light.png", "home.c.dark.png", "home.c.light.png", "home.c.ic.dark.png",
                      "home.d.dark.png", "home.d.light.actual.png", "home.old.dark.png", "notes.png"])
        let (findings, tally) = coverage.audit()
        XCTAssertEqual(findings, [
            "home.c: listed twice in PENDING",
            "home.a: neither green nor in PENDING",
            "home.b: green, so its line leaves PENDING",
            "home.d: neither green nor in PENDING",
            "home.gone: in PENDING, but STORIES.md does not hold it",
            "home.stray: a story file STORIES.md does not hold",
            "home.old.dark.png: a golden STORIES.md does not hold",
            "notes.png: not a golden of a story",
        ])
        XCTAssertEqual(tally, Coverage.Tally(green: 1, pending: 3, orphans: 4))
        XCTAssertEqual(coverage.status("home.c"), "today", "a golden of today's look is still pending")
        XCTAssertEqual(coverage.status("phone.explainer"), "excluded")
    }

    func testTheCatalogueReadsEveryStoryUnderItsSection() {
        let catalogue = Catalogue.parse("# Stories\n\n## Menu bar\n\n### `menubar.count`\n\nShows.\n\n## Home\n\n### `home.needs`\n### `home.fine`\n")
        XCTAssertEqual(catalogue.entries, [
            .init(id: "menubar.count", section: "Menu bar"),
            .init(id: "home.needs", section: "Home"),
            .init(id: "home.fine", section: "Home"),
        ])
    }
}
